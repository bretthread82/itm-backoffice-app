/**
 * BaseController provides a convenient place for loading components
 * and performing functions that are needed by all your controllers.
 *
 * Extend this class in any new controllers:
 * ```
 *     class Home extends BaseController
 * ```
 *
 * For security, be sure to declare any new methods as protected or private.
 */
abstract class BaseController extends Controller
{
    /**
     * Be sure to declare properties for any property fetch you initialized.
     * The creation of dynamic property is deprecated in PHP 8.2.
     */

    // protected $session;

    /**
     * @param CLIRequest|IncomingRequest $request
     *
     * @return void
     */
    public function initController(RequestInterface $request, ResponseInterface $response, LoggerInterface $logger)
    {
        // Load here all helpers you want to be available in your controllers that extend BaseController.
        // Caution: Do not put the this below the parent::initController() call below.
        // $this->helpers = ['form', 'url'];

        // Caution: Do not edit this line.
        parent::initController($request, $response, $logger);

        // Preload any models, libraries, etc, here.
        // $this->session = service('session');
    }

    /**
     * The company a screen should narrow to: an explicit choice (query string) wins, otherwise the
     * company switcher's selection, otherwise 0 for "everything the user may see". This only narrows;
     * access is always enforced by service('scope')->restrict().
     */
    protected function scopedCompany(?int $explicit = null): int
    {
        if ($explicit !== null && $explicit > 0) {
            return $explicit;
        }

        return service('activeCompany')->current((int) auth()->id()) ?? 0;
    }
}
